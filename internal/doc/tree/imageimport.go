package tree

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"dgs-toolbox/internal/doc/imagepdf"
	"dgs-toolbox/internal/verifiedcopy"
)

// Original identifies the archived input image by content, beside its PDF.
type Original struct {
	Digest    string `yaml:"digest" json:"digest"`
	Extension string `yaml:"extension" json:"extension"`
}

// OriginalPath resolves a validated archive reference. Empty rejects malformed
// sidecar paths rather than allowing a reference outside the Item directory.
func OriginalPath(root, id string, o Original) string {
	if id == "" || id == "." || id == ".." || filepath.Base(id) != id {
		return ""
	}
	digest, err := hex.DecodeString(o.Digest)
	if err != nil || len(digest) != sha256.Size || strings.ToLower(o.Digest) != o.Digest || !imagepdf.Supported("image"+o.Extension) || strings.ToLower(o.Extension) != o.Extension || filepath.Ext("image"+o.Extension) != o.Extension {
		return ""
	}
	return filepath.Join(Dir(root, id), o.Digest+o.Extension)
}

type imageInput struct {
	pdf, source, name string
	expectedPDF       string
	original          *Original
	inputDigest       string
	cleanup           func()
}

// prepareInput snapshots the image once, outside the tree: conversion and
// optional archival then use the exact same original bytes.
func prepareInput(ctx context.Context, source string) (imageInput, error) {
	in := imageInput{pdf: source, name: filepath.Base(source), cleanup: func() {}}
	if !imagepdf.Supported(source) {
		return in, nil
	}
	data, err := imagepdf.Read(source)
	if err != nil {
		return in, err
	}
	sum := sha256.Sum256(data)
	in.inputDigest = hex.EncodeToString(sum[:])
	in.original = &Original{Digest: hex.EncodeToString(sum[:]), Extension: strings.ToLower(filepath.Ext(source))}
	dir, err := os.MkdirTemp("", "dgs-doc-import-*")
	if err != nil {
		return in, err
	}
	in.cleanup = func() { os.RemoveAll(dir) }
	in.source = filepath.Join(dir, "original"+in.original.Extension)
	if err := os.WriteFile(in.source, data, 0600); err != nil {
		in.cleanup()
		return in, err
	}
	output, err := imagepdf.Convert(ctx, source, data)
	if err != nil {
		in.cleanup()
		return in, err
	}
	sumPDF := sha256.Sum256(output)
	in.expectedPDF = hex.EncodeToString(sumPDF[:])
	in.pdf = filepath.Join(dir, "converted.pdf")
	if err := os.WriteFile(in.pdf, output, 0600); err != nil {
		in.cleanup()
		return in, err
	}
	return in, nil
}

func (in imageInput) archive(ctx context.Context, root, id string, keep bool) (func(), error) {
	undo := func() {}
	if !keep || in.original == nil {
		return undo, nil
	}
	path := OriginalPath(root, id, *in.original)
	if path == "" {
		return undo, fmt.Errorf("invalid original image reference")
	}
	if _, err := os.Lstat(path); err == nil {
		digest, err := FileDigest(path)
		if err != nil {
			return undo, err
		}
		if digest != in.original.Digest {
			return undo, fmt.Errorf("stored original digest mismatch")
		}
		return undo, nil
	} else if !os.IsNotExist(err) {
		return undo, err
	}
	result, err := verifiedcopy.Copy(ctx, verifiedcopy.Request{Source: in.source, Destination: path})
	if err != nil {
		return undo, err
	}
	undo = func() { os.Remove(path) }
	if result.Digest != in.original.Digest {
		undo()
		return func() {}, fmt.Errorf("original image digest mismatch")
	}
	return undo, nil
}

func (in imageInput) annotate(item *Item, ref string, keep bool) {
	if in.inputDigest == "" {
		return
	}
	for n := range item.Revisions {
		r := &item.Revisions[n]
		if r.Ref() != ref {
			continue
		}
		if in.original != nil {
			if r.SourceDigest != "" && r.SourceDigest != in.inputDigest && !slices.Contains(r.SourceDigests, r.SourceDigest) {
				r.SourceDigests = append(r.SourceDigests, r.SourceDigest)
			}
			r.Source = in.name
			r.SourceDigest = in.inputDigest
			if keep {
				r.Original = in.original
			}
		} else if r.SourceDigest != in.inputDigest && !slices.Contains(r.SourceDigests, in.inputDigest) {
			r.SourceDigests = append(r.SourceDigests, in.inputDigest)
		}
	}
}

// Reused snapshots retain an already archived input. An explicit retention
// request for different bytes is a conflict, never a silent success.
func (in *imageInput) preserveProvenance(item Item, ref string, keep bool) error {
	if in.original == nil {
		return nil
	}
	r, ok := item.Revision(ref)
	if !ok || r.Original == nil {
		return nil
	}
	if r.Original.Digest == in.original.Digest {
		// Extension aliases such as .jpg and .jpeg still name the same bytes.
		in.original = r.Original
		return nil
	}
	if keep {
		return fmt.Errorf("this snapshot already has a different archived original; keep the existing original or import different document content")
	}
	in.original = nil
	return nil
}

// digest verifies generated bytes independently after their temporary write.
func (in imageInput) digest() (string, error) {
	actual, err := FileDigest(in.pdf)
	if err != nil {
		return "", err
	}
	if in.expectedPDF != "" && actual != in.expectedPDF {
		return "", fmt.Errorf("converted PDF SHA-256 readback mismatch")
	}
	return actual, nil
}
